// Generates standalone.html: index.html with scheduler.js inlined as a classic script, so the app works when
// opened directly from disk (file://), where browsers block ES-module imports. The Web Worker is built from a Blob.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const sched = fs.readFileSync(path.join(root, 'scheduler.js'), 'utf8');
let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');

const names = [...sched.matchAll(/^export\s+(?:async\s+)?(?:function|const|class|let)\s+([A-Za-z0-9_$]+)/gm)].map((m) => m[1]);
const body = sched.replace(/^export\s+/gm, '');

const inline = `
      // ---- inlined scheduler.js (generated by scripts/make-standalone.mjs; edit scheduler.js, not this) ----
      function __schedulerFactory() {
${body}
        return { ${names.join(', ')} };
      }
      const __S = __schedulerFactory();
      const { ${names.join(', ')} } = __S;
      let __worker = null, __nextId = 1;
      const __pending = new Map();
      function runScheduler(workload, config, options) {
        try {
          if (!__worker) {
            const full = 'const __schedulerFactory = ' + __schedulerFactory.toString() + ';\\n' +
              'const __S = __schedulerFactory();\\n' +
              'self.onmessage = (e) => { const {id, workload, config, options} = e.data; ' +
              'try { self.postMessage({id, result: __S.generateTimetable(workload, config, options)}); } ' +
              'catch (err) { self.postMessage({id, error: String(err && err.stack || err)}); } };';
            __worker = new Worker(URL.createObjectURL(new Blob([full], { type: 'text/javascript' })));
            __worker.onmessage = (e) => {
              const p = __pending.get(e.data.id);
              if (!p) return;
              __pending.delete(e.data.id);
              e.data.error ? p.reject(new Error(e.data.error)) : p.resolve(e.data.result);
            };
            __worker.onerror = (e) => { __pending.forEach((p) => p.reject(new Error(e.message || 'Worker error'))); __pending.clear(); __worker = null; };
          }
          return new Promise((resolve, reject) => { const id = __nextId++; __pending.set(id, { resolve, reject }); __worker.postMessage({ id, workload, config, options }); });
        } catch (e) {
          __worker = null;
          return new Promise((resolve) => setTimeout(() => resolve(__S.generateTimetable(workload, config, options)), 30));
        }
      }
`;

const re = /<script type="module">[\s\S]*?import \{ runScheduler \} from '\.\/solverClient\.js';\n/;
if (!re.test(html)) throw new Error('index.html module header not found');
html = html.replace(re, () => `<script>\n${inline}\n`);
fs.writeFileSync(path.join(root, 'standalone.html'), html);
console.log(`standalone.html written (${(html.length / 1024).toFixed(0)} KB, ${names.length} exports inlined)`);
